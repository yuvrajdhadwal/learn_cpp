/* *
 * Containers provide functionality for:
 *      1. Creating empty container (via a constructor)
 *      2. Inserting new objects into that container
 *      3. Removing objects from Containers
 *      4. Count how many objects are in container
 *      5. Empty container of objects
 *      6. Provide access to stored objects
 *      7. Sort elements (optional)
 *
 *      Uses "Member of" Relationship
 *
 *      Value Containers: Composition: store copies of objects that they are holding
 *      Reference Containers: Aggregation: store pointers or references to other objects
 *      
 *      You can make your constructors list initialization with std::initializer_list
 *      which is in #include <initializer_list>
 * */
